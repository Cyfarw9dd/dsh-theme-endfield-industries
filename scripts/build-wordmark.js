'use strict'
/**
 * scripts/build-wordmark.js — embed the ENDFIELD wordmark mask into src/styles/generated.css.
 *
 * SOURCE OF THE ASSET (provenance, do not lose):
 *   The official site's own background wordmark on /operator. There is no image
 *   file for it: the site draws it as CSS text (HallowText_hollowText) in
 *   Novecento Sans Wide Bold with a -45deg hatch gradient clipped to the glyphs
 *   (endfield.hypergryph.com/#operator, retrieved 2026-10-24).
 *   Because that typeface is commercial (Fontspring / MyFonts / Adobe Fonts,
 *   Synthview), no font file is shipped. The mark was rendered once from the
 *   site's own webfont — the release the page loads:
 *     https://web.hycdn.cn/endfield/official-v4/_next/static/media/font/
 *       Novecentosanswide-Bold.3fdbac.woff2
 *   as a TWO-LINE lockup:
 *     "ENDFIELD"    1200px, letter-spacing -0.08em, line-height 1
 *                    (the operator page's own metrics; ink 5132x840)
 *     "INDUSTRIES"  1200px, letter-spacing -0.08em, line-height 1
 *                    (the OWNER's call: same type size, i.e. equal cap height.
 *                     It is 10 letters to ENDFIELD's 8, so the second line is
 *                     wider; both are centre-aligned into one two-line block)
 *   LEADING: the lines are stacked with a 40px ink gap at this 1200px type size
 *   (≈4.8% of the cap height) — the tight stack of the official loading screen's
 *   giant wordmark band (endfield.hypergryph.com / the game's loading plate),
 *   not the airy lockup gap. This script builds the repeating TILE from this lockup:
 *   [lockup right part][clear gap 3000][lockup left part], with the gap centre at
 *   62% of the tile; the CSS repeats the tile and puts the emblem in the gap.
 *   Neither the repetition nor the emblem is part of the checked-in lockup.
 *   The composition is this theme's own — the site has no two-line loading
 *   lockup — but every glyph belongs to the official wordmark. The 6171x1754
 *   black-on-white render is checked in as
 *     assets/endfield-wordmark-source.png
 *     (sha256 c92f209187c5ac69c351095827bac21f8f7a2173840e9dc4b234cf21565e6471)
 *   so the trace below is auditable. It was vectorised with potrace 1.16:
 *     potrace -b svg -O 0.2 --turdsize 2
 *   and the traced outline is checked in as assets/endfield-wordmark.svg
 *   (pure path data, no scripts/handlers). The artwork is Hypergryph brand art —
 *   the same fan-use status as every other brand-derived asset in this
 *   repository (see docs/credits.md（素材归属）). potrace is not a build
 *   dependency; the traced SVG is checked in, like the hero-logo masks.
 *
 * WHAT THIS SCRIPT DOES. Same marker-block splice contract as build-emblem.js:
 * strip the XML prolog/element ids/whitespace, encode the minimal SVG as a data
 * URI and splice it into generated.css as --edge-wordmark, used as a CSS MASK in
 * ALPHA mode (the paths' own alpha is the shape, so the stylesheet's hatch
 * gradient supplies the ink and currentColor supplies the colour).
 *
 *   node scripts/build-wordmark.js          # rewrite the marked region
 *   node scripts/build-wordmark.js --check  # exit 1 if the generated region drifted
 */
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const SRC = path.join(ROOT, 'assets', 'endfield-wordmark.svg')
const { stylePath, GENERATED_FILE } = require('./lib/sources.js')
const CLIENT = stylePath(GENERATED_FILE)
const BEGIN = '/* WORDMARK_MASK_BEGIN (generated by scripts/build-wordmark.js — do not edit by hand) */'
const END = '/* WORDMARK_MASK_END */'
const checkOnly = process.argv.includes('--check')

/* ---- strip editor metadata down to a minimal single-line SVG ---- */
const minimizeSvg = (src) => {
  let s = src
  s = s.replace(/<\?xml[^>]*\?>/g, '')
  s = s.replace(/<!--[\s\S]*?-->/g, '')
  s = s.replace(/<metadata>[\s\S]*?<\/metadata>/g, '')
  const vb = s.match(/viewBox="([^"]+)"/)
  if (!vb) throw new Error('no viewBox in the source SVG — cannot rebuild the root')
  const open = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb[1]}">`
  s = s.replace(/<svg[\s\S]*?>/, open)
  s = s.replace(/\s(id|class)="[^"]*"/g, '')
  s = s.replace(/\s+/g, ' ').replace(/\s*<\s*/g, '<').replace(/\s*>\s*/g, '>').trim()
  if (!/<path/.test(s) || !s.endsWith('</svg>')) {
    throw new Error('minimized SVG failed its shape sanity check')
  }
  return s
}

/* ---- build the repeating TILE: one lockup + a clear gap at 62% ---- */
/* The in-game plate does not stamp the logo ON the giant letters: the repeated
   wordmark leaves a wide clear gap between instances and the logo sits IN that
   gap (see the reference: the left instance ends, the gap carries the emblem,
   the next instance begins). Tile layout, in mask units:
     [ lockup split..W ][ transparent gap G ][ lockup 0..split ]
   The gap centre is placed at 62% of the tile, and the CSS positions the tile
   at 62% of the host, so the gap lands exactly at the emblem's anchor. */
const TILE_GAP_FRAC = 0.62
const buildTileSvg = (lockupSrc) => {
  const vb = lockupSrc.match(/viewBox="([^"]+)"/)
  if (!vb) throw new Error('no viewBox in the lockup SVG — cannot build the tile')
  const parts = vb[1].trim().split(/\s+/).map(Number)
  const W = parts[2]
  const H = parts[3]
  if (!(W > 0 && H > 0)) throw new Error('bad lockup viewBox: ' + vb[1])
  const inner = lockupSrc.replace(/<svg[\s\S]*?>/, '').replace(/<\/svg>\s*$/, '')
  if (!/<path/.test(inner)) throw new Error('lockup SVG has no paths')
  const G = 3000
  const T = W + G
  /* gap centre = (W - split) + G/2 = TILE_GAP_FRAC * T */
  const split = Math.round(W + G / 2 - TILE_GAP_FRAC * T)
  const rightW = W - split
  const gapX = rightW
  const leftX = rightW + G
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 ' + T + ' ' + H + '">' +
    '<defs><g id="w">' + inner + '</g>' +
    '<clipPath id="cr"><rect x="0" y="0" width="' + rightW + '" height="' + H + '"/></clipPath>' +
    '<clipPath id="cl"><rect x="' + leftX + '" y="0" width="' + split + '" height="' + H + '"/></clipPath></defs>' +
    '<g clip-path="url(#cr)"><use href="#w" xlink:href="#w" transform="translate(' + (-split) + ' 0)"/></g>' +
    '<g clip-path="url(#cl)"><use href="#w" xlink:href="#w" transform="translate(' + leftX + ' 0)"/></g>' +
    '</svg>'
  return svg
}

/* ---- splice the data URI into generated.css between the markers ---- */
const main = () => {
  const svg = buildTileSvg(fs.readFileSync(SRC, 'utf8'))
  const uri = 'data:image/svg+xml;base64,' + Buffer.from(svg, 'utf8').toString('base64')
  const src = fs.readFileSync(CLIENT, 'utf8')
  const beginIdx = src.indexOf(BEGIN)
  const endIdx = src.indexOf(END)
  if (beginIdx < 0 || endIdx < 0 || endIdx < beginIdx) {
    throw new Error('WORDMARK_MASK markers missing from src/styles/generated.css — see the watermark CSS block')
  }
  /* The declaration MUST live inside a body{} rule: a bare top-level declaration
     is invalid CSS, and the parser's error recovery then swallows the NEXT rule's
     selector as its block. check.js pins this shape. */
  const block = BEGIN + '\n' +
    `  /* Vector ENDFIELD / INDUSTRIES wordmark TILE (two equal-height lines + a\n` +
    `     clear gap at 62% for the emblem), built from the traced lockup (see\n` +
    `     scripts/build-wordmark.js for provenance). SVG ${svg.length} bytes / ${Math.round(uri.length / 1024)}KB base64.\n` +
    `     Alpha mask; CSS repeats it in x so the emblem lands IN the gap.\n` +
    `     Regenerate: node scripts/build-wordmark.js */\n` +
    `  body { --edge-wordmark: url("${uri}"); }\n` +
    '  ' + END
  const next = src.slice(0, beginIdx) + block + src.slice(endIdx + END.length)
  if (next === src) {
    console.log(`ok       wordmark mask unchanged (minimized SVG ${svg.length} bytes, ${Math.round(uri.length / 1024)}KB base64)`)
    return
  }
  if (checkOnly) {
    console.error('DRIFTED  generated.css wordmark region — run: node scripts/build-wordmark.js')
    process.exitCode = 1
    return
  }
  fs.writeFileSync(CLIENT, next)
  console.log(`updated  generated.css wordmark mask (minimized SVG ${svg.length} bytes, ${Math.round(uri.length / 1024)}KB base64)`)
}

main()
