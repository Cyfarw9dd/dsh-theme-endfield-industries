'use strict'
/**
 * scripts/build-emblem.js — embed the watermark logo masks into src/styles/generated.css.
 *
 * SOURCE OF ASSET 1 — the ENGLISH lockup (shipped default):
 *   assets/endfield-industries.svg is the vectorized Endfield Industries emblem
 *   (barcode wordmark + inverted triangle) from the open fan repository
 *     https://github.com/Yue-plus/endfield_icons  (svg/endfield-industries.svg)
 *   downloaded 2026-09-30; original sha256
 *     3e2af120ec6c86d2132448e7fbd4264b50e7258276c1beabb2bf3fa666200025
 *   The repository declares MIT, but the underlying artwork is Hypergryph
 *   brand art — same fan-use status as every other brand-derived asset here
 *   (see docs/credits.md（素材归属）). Adoption of this third-party source was explicitly
 *   approved by the repository owner (the local download-source policy exempts
 *   this one file by name).
 *
 * SOURCE OF ASSET 2 — the CHINESE lockup (settings › 背景 › 徽标版本 = 中文版):
 *   assets/endfield-industries-logo-zh.svg, sha256
 *     5fd4d50071c8bdbec0eb75c189efb35379afa253fa577b96179cbcdb231fb854
 *   It is a LOCAL POTRACE TRACE, not an official vector: the repository owner
 *   supplied the PRTS file page (2026-10-25) and the PNG was archived as
 *   assets/endfield-industries-logo-zh.png (430x372, sha256
 *     724fbf04a4a661c5c16688c49febb68b2be0bd8fbfe7c83895350876d115be04);
 *   the trace recipe (alpha -> 4x Lanczos -> potrace -a 1.334 -O 0.5
 *   --turdsize 4) and the source/licensing note live in docs/credits.md.
 *   It is consumed here only when the 「徽标版本」 row selects 中文版; the default
 *   (en) keeps the shipped look byte-identical.
 *
 * WHAT THIS SCRIPT DOES. The English download carries editor metadata (Adobe
 * Illustrator generator comment, Inkscape/Sodipodi namespace declarations,
 * element ids, pretty-print whitespace) that is dead weight in a data URI; the
 * Chinese trace carries potrace's prolog/metadata. The build strips all of that
 * to a single-line minimal SVG and splices BOTH into generated.css in ONE body
 * rule as --edge-emblem / --edge-emblem-zh, used as CSS MASKS in ALPHA mode: the
 * paths' own alpha channel IS the shape, so the stylesheet's currentColor paints
 * the mark at any scale — vector, so it is crisp at every zoom and
 * devicePixelRatio. The stylesheet picks the zh mask only under
 * body[data-edge-wm-emblem='zh']; both masks share the same square box and
 * `contain` sizing (their ink aspects are 1.131 / 1.156, so the swap does not
 * change the mark's apparent size).
 *
 * Pure Node, no dependencies. Same marker-block splice contract as before:
 *   node scripts/build-emblem.js          # rewrite the marked region in src/styles/generated.css
 *   node scripts/build-emblem.js --check  # exit 1 if the generated region drifted
 */
const fs = require('fs')
const path = require('path')
const zlib = require('zlib') // kept: crc/deflate helpers removed with the PNG pipeline

const ROOT = path.join(__dirname, '..')
const SRC_EN = path.join(ROOT, 'assets', 'endfield-industries.svg')
const SRC_ZH = path.join(ROOT, 'assets', 'endfield-industries-logo-zh.svg')
const { stylePath, GENERATED_FILE } = require('./lib/sources.js')
const CLIENT = stylePath(GENERATED_FILE)
const BEGIN = '/* EMBLEM_MASK_BEGIN (generated by scripts/build-emblem.js — do not edit by hand) */'
const END = '/* EMBLEM_MASK_END */'
const checkOnly = process.argv.includes('--check')

/* ---- strip editor metadata down to a minimal single-line SVG ---- */
const minimizeSvg = (src) => {
  let s = src
  // XML prolog and the Illustrator generator comment (comments may span lines).
  s = s.replace(/<\?xml[^>]*\?>/g, '')
  s = s.replace(/<!--[\s\S]*?-->/g, '')
  // Rebuild the root element: keep ONLY the default namespace and the viewBox.
  const vb = s.match(/viewBox="([^"]+)"/)
  if (!vb) throw new Error('no viewBox in the source SVG — cannot rebuild the root')
  const open = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb[1]}">`
  s = s.replace(/<svg[\s\S]*?>/, open)
  // Group/shape ids and editor attributes are inert here; drop them.
  s = s.replace(/\s(id|class)="[^"]*"/g, '')
  s = s.replace(/<g\s*>/g, '<g>')
  // Path data separates coordinates with whitespace; collapse ALL whitespace to
  // single spaces (safe for d/points values) and drop inter-tag padding.
  s = s.replace(/\s+/g, ' ').replace(/\s*<\s*/g, '<').replace(/\s*>\s*/g, '>').trim()
  if (!/<path/.test(s) || !s.endsWith('</svg>')) {
    throw new Error('minimized SVG failed its shape sanity check')
  }
  return s
}

const toUri = (file) => {
  const svg = minimizeSvg(fs.readFileSync(file, 'utf8'))
  return {
    name: path.basename(file),
    svg,
    uri: 'data:image/svg+xml;base64,' + Buffer.from(svg, 'utf8').toString('base64'),
  }
}

/* ---- splice the data URIs into src/styles/generated.css between the markers ---- */
const main = () => {
  const en = toUri(SRC_EN)
  const zh = toUri(SRC_ZH)
  const src = fs.readFileSync(CLIENT, 'utf8')
  const beginIdx = src.indexOf(BEGIN)
  const endIdx = src.indexOf(END)
  if (beginIdx < 0 || endIdx < 0 || endIdx < beginIdx) {
    throw new Error('EMBLEM_MASK markers missing from src/styles/generated.css — see the watermark CSS block')
  }
  const kb = (x) => Math.round(x.uri.length / 1024)
  /* The two declarations MUST live inside ONE body{} rule: a bare top-level
     declaration is invalid CSS, and the parser's error recovery then swallows
     the NEXT rule's selector as its block (measured: it ate
     [data-endfield-contour] and the sheet silently lost it). check.js pins
     this shape — including that both masks sit in the SAME rule. */
  const block = BEGIN + '\n' +
    `  /* Vector emblem masks, TWO language variants of the same lockup, both\n` +
    `     alpha masks (the paths' alpha is the shape) painted by currentColor:\n` +
    `       --edge-emblem     English (Yue-plus/endfield_icons vectorization)\n` +
    `       --edge-emblem-zh  Chinese (local potrace trace of the PRTS-archived PNG)\n` +
    `     Provenance for both in scripts/build-emblem.js + docs/credits.md.\n` +
    `     Minimized SVG ${en.svg.length} / ${zh.svg.length} bytes, ${kb(en)}KB / ${kb(zh)}KB base64.\n` +
    `     Regenerate: node scripts/build-emblem.js */\n` +
    `  body { --edge-emblem: url("${en.uri}"); --edge-emblem-zh: url("${zh.uri}"); }\n` +
    '  ' + END
  const next = src.slice(0, beginIdx) + block + src.slice(endIdx + END.length)
  const summary = `minimized SVG ${en.svg.length}/${zh.svg.length} bytes (${kb(en)}KB/${kb(zh)}KB base64)`
  if (next === src) {
    console.log(`ok       emblem masks unchanged (${summary})`)
    return
  }
  if (checkOnly) {
    console.error('DRIFTED  generated.css emblem region — run: node scripts/build-emblem.js')
    process.exitCode = 1
    return
  }
  fs.writeFileSync(CLIENT, next)
  console.log(`updated  generated.css emblem masks (${summary})`)
}

main()
